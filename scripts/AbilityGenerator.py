#!/usr/bin/env python3
"""AbilityGenerator — build ability definitions from CSV.

Reads `abilities.csv` (identity, targeting, costs, timing, projectile) and
`ability_effects.csv` (trigger-tagged consequences, joined on `ability_id`),
validates both, and generates normal `AbilityDefinition`s:

  - `src/abilities/generated.rs`: one `fn <id>() -> AbilityDefinition` per ability,
    built with the same builders / `AbilityEffectEntry` rows as hand-written abilities
    in `src/abilities/catalog.rs`. Generated definitions take precedence over
    hand-written ones with the same `AbilityId`.
  - `src/components.rs`: `AbilityId` variant, display name, ultimate flag, max rank.

Re-running overwrites abilities that already exist; abilities missing from the CSV
are kept. Blank cells mean "not applicable"; `75|150|225|300` gives one value per level.

Usage:
  python3 scripts/AbilityGenerator.py                       # data/abilities.csv + data/ability_effects.csv
  python3 scripts/AbilityGenerator.py my_abilities.csv my_effects.csv
  python3 scripts/AbilityGenerator.py --check                # validate only
  python3 scripts/AbilityGenerator.py --dry-run              # print generated code
"""

