#!/usr/bin/env python3
"""RoomGenerator — build Story Mode room definitions from CSV.

Reads `rooms.csv` (identity, kind, layout, depth range, odds, reward, shop) and
`room_spawns.csv` (creep groups per room), validates both, and writes the whole of
`src/story/room_catalog.rs`: the `RoomId` enum, `pub static ROOMS: &[RoomDefinition]` and
`pub const FINAL_DEPTH: u32`. The file is regenerated from scratch, so re-running the
generator is byte-identical until a CSV changes.

`rooms.csv` columns:
  id, name, kind (safe | combat | elite | boss), layout (a `RoomLayoutId` variant in snake case,
  read from the `room_layouts` markers of `src/story/layouts.rs`), min_depth, max_depth,
  weight (relative odds in the exit draw, default 1), reward (none | gold | neutral_item),
  reward_amount (gold only), shop (TRUE spawns an item shop), description.
`room_spawns.csv` columns:
  room_id, spawn_index, creep (melee | ranged), class (normal | captain | boss), count,
  x, z (world offset from the room centre; `count` creeps stand on a ring around it).

Rules the generator enforces: one `safe` room at depth 0 with a shop and no spawns; every other
room starts at depth 1 or later; `boss` rooms sit exactly at FINAL_DEPTH (the largest boss
`max_depth`) and nothing else reaches it; every depth below FINAL_DEPTH offers a non-boss room;
every non-safe room has at least one spawn; a `gold` reward needs `reward_amount`.
Spawn positions are checked against the layout geometry by a Rust test, not here.

Usage:
  python3 scripts/RoomGenerator.py                      # data/rooms.csv + data/room_spawns.csv
  python3 scripts/RoomGenerator.py my_rooms.csv my_spawns.csv
  python3 scripts/RoomGenerator.py --check               # validate only
  python3 scripts/RoomGenerator.py --dry-run             # print generated code
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from generator_common import (  # noqa: E402
    Report,
    Row,
    check_id,
    f32,
    parse_bool,
    parse_enum,
    parse_scalar,
    read_csv,
    rust_str,
    rustfmt,
    to_pascal_case,
)

ROOM_COLUMNS = ("id", "name", "kind", "layout", "min_depth", "max_depth")
SPAWN_COLUMNS = ("room_id", "spawn_index", "creep", "class", "count", "x", "z")

KINDS = {"safe": "Safe", "combat": "Combat", "elite": "Elite", "boss": "Boss"}
REWARDS = ("none", "gold", "neutral_item")
CREEPS = ("melee", "ranged")
CLASSES = {"normal": "Normal", "captain": "Captain", "boss": "Boss"}

LAYOUTS_PATH = Path("src") / "story" / "layouts.rs"
CATALOG_PATH = Path("src") / "story" / "room_catalog.rs"

HEADER = """\
//! Generated by `scripts/RoomGenerator.py` from `data/rooms.csv` and
//! `data/room_spawns.csv` — edit the CSVs and re-run the generator.

use bevy::prelude::Vec2;

use super::layouts::RoomLayoutId;
use super::rooms::{RoomDefinition, RoomGoal, RoomKind, RoomReward, RoomSpawn};
use crate::components::CreepClass;
"""


@dataclass
class Spawn:
    row: Row
    index: int
    ranged: bool
    class_: str
    count: int
    x: float
    z: float


@dataclass
class Room:
    row: Row
    id: str
    variant: str
    name: str
    kind: str
    layout: str
    min_depth: int
    max_depth: int
    weight: int
    reward: str
    reward_amount: int | None
    shop: bool
    description: str
    spawns: list[Spawn] = field(default_factory=list)


def find_layouts(repo_root: Path) -> set[str]:
    """`RoomLayoutId` variants (PascalCase) between the `room_layouts` markers."""
    text = (repo_root / LAYOUTS_PATH).read_text(encoding="utf-8")
    match = re.search(r"//\s*<room_layouts>(.*?)//\s*</room_layouts>", text, re.DOTALL)
    if not match:
        raise SystemExit(f"{LAYOUTS_PATH}: missing the <room_layouts> marker region")
    return set(re.findall(r"^\s*([A-Z][A-Za-z0-9]*)\s*,", match.group(1), re.MULTILINE))


def parse_room(row: Row, layouts: set[str], report: Report) -> Room | None:
    ident = check_id(row, "id", report)
    name = row.get("name")
    if not name:
        report.error(row.file, row.line, "name", "", "required")
    kind = parse_enum(row, "kind", list(KINDS), report)
    layout = row.get("layout").lower()
    if not layout:
        report.error(row.file, row.line, "layout", "", "required")
    elif to_pascal_case(layout) not in layouts:
        known = ", ".join(sorted(re.sub(r"(?<!^)(?=[A-Z])", "_", v).lower() for v in layouts))
        report.error(row.file, row.line, "layout", layout, f"no such RoomLayoutId variant; expected one of: {known}")
    min_depth = parse_scalar(row, "min_depth", report, integer=True, minimum=0)
    max_depth = parse_scalar(row, "max_depth", report, integer=True, minimum=0)
    for column, value in (("min_depth", min_depth), ("max_depth", max_depth)):
        if value is None and not row.get(column):
            report.error(row.file, row.line, column, "", "required")
    if min_depth is not None and max_depth is not None and min_depth > max_depth:
        report.error(row.file, row.line, "max_depth", row.get("max_depth"), "must be at least min_depth")
    weight = parse_scalar(row, "weight", report, integer=True, minimum=1)
    reward = parse_enum(row, "reward", REWARDS, report, required=False) or "none"
    amount = parse_scalar(row, "reward_amount", report, integer=True, minimum=1)
    if reward == "gold" and amount is None:
        report.error(row.file, row.line, "reward_amount", row.get("reward_amount"), "a gold reward needs reward_amount >= 1")
    if reward != "gold" and row.get("reward_amount"):
        report.warn(row.file, row.line, "reward_amount", row.get("reward_amount"), "ignored: only gold rewards have an amount")
    shop = parse_bool(row, "shop", report) or False
    if ident is None or not name or kind is None or min_depth is None or max_depth is None:
        return None
    return Room(
        row=row,
        id=ident,
        variant=to_pascal_case(ident),
        name=name,
        kind=kind,
        layout=layout,
        min_depth=int(min_depth),
        max_depth=int(max_depth),
        weight=int(weight) if weight is not None else 1,
        reward=reward,
        reward_amount=int(amount) if amount is not None else None,
        shop=shop,
        description=row.get("description"),
    )


def parse_spawn(row: Row, report: Report) -> tuple[str, Spawn] | None:
    room_id = row.get("room_id")
    if not room_id:
        report.error(row.file, row.line, "room_id", "", "required")
    index = parse_scalar(row, "spawn_index", report, integer=True, minimum=0)
    if index is None and not row.get("spawn_index"):
        report.error(row.file, row.line, "spawn_index", "", "required")
    creep = parse_enum(row, "creep", CREEPS, report)
    class_ = parse_enum(row, "class", list(CLASSES), report)
    count = parse_scalar(row, "count", report, integer=True, minimum=1)
    if count is None and not row.get("count"):
        report.error(row.file, row.line, "count", "", "required")
    x = parse_scalar(row, "x", report)
    z = parse_scalar(row, "z", report)
    for column, value in (("x", x), ("z", z)):
        if value is None and not row.get(column):
            report.error(row.file, row.line, column, "", "required")
    if not room_id or index is None or creep is None or class_ is None or count is None or x is None or z is None:
        return None
    return room_id, Spawn(row, int(index), creep == "ranged", class_, int(count), x, z)


def load(rooms_csv: Path, spawns_csv: Path, layouts: set[str]) -> tuple[list[Room], Report]:
    report = Report()
    room_rows = read_csv(rooms_csv, ROOM_COLUMNS, report)
    spawn_rows = read_csv(spawns_csv, SPAWN_COLUMNS, report)

    rooms: list[Room] = []
    first_line: dict[str, int] = {}
    variants: dict[str, str] = {}
    for row in room_rows:
        room = parse_room(row, layouts, report)
        ident = row.get("id")
        if ident in first_line:
            report.error(row.file, row.line, "id", ident, f"duplicate room id (first defined on line {first_line[ident]})")
            continue
        if ident:
            first_line[ident] = row.line
        if room is None:
            continue
        if room.variant in variants:
            report.error(row.file, row.line, "id", ident, f"maps to RoomId::{room.variant}, same as {variants[room.variant]!r}")
            continue
        variants[room.variant] = ident
        rooms.append(room)

    by_id = {room.id: room for room in rooms}
    for row in spawn_rows:
        parsed = parse_spawn(row, report)
        if parsed is None:
            continue
        room_id, spawn = parsed
        room = by_id.get(room_id)
        if room is None:
            report.error(row.file, row.line, "room_id", room_id, "no room with this id in the rooms CSV")
            continue
        if any(other.index == spawn.index for other in room.spawns):
            report.error(row.file, row.line, "spawn_index", row.get("spawn_index"), f"duplicate spawn_index for room {room_id}")
            continue
        room.spawns.append(spawn)
    for room in rooms:
        room.spawns.sort(key=lambda s: s.index)

    validate_rooms(rooms, report)
    return rooms, report


def final_depth(rooms: list[Room]) -> int | None:
    bosses = [room.max_depth for room in rooms if room.kind == "boss"]
    return max(bosses) if bosses else None


def validate_rooms(rooms: list[Room], report: Report) -> None:
    def err(room: Room, field_name: str, message: str) -> None:
        report.error(room.row.file, room.row.line, field_name, room.row.get(field_name), message)

    safe = [room for room in rooms if room.kind == "safe"]
    if len(safe) != 1:
        report.error(str(rooms[0].row.file) if rooms else "rooms", None, "kind", None, f"exactly one safe room is required (found {len(safe)})")
    for room in safe:
        if (room.min_depth, room.max_depth) != (0, 0):
            err(room, "min_depth", "the safe room sits at depth 0 only (min_depth and max_depth 0)")
        if not room.shop:
            err(room, "shop", "the safe room needs shop=TRUE")
        if room.spawns:
            err(room, "kind", "a safe room has no spawns")
    for room in rooms:
        if room.kind == "safe":
            continue
        if room.min_depth < 1:
            err(room, "min_depth", "combat, elite and boss rooms start at depth 1 or later (depth 0 is the safe room)")
        if not room.spawns:
            err(room, "kind", f"a {room.kind} room needs at least one row in the spawns CSV")

    final = final_depth(rooms)
    bosses = [room for room in rooms if room.kind == "boss"]
    if not bosses:
        report.error(rooms[0].row.file if rooms else "rooms", None, "kind", None, "at least one boss room is required")
        return
    for room in bosses:
        if room.min_depth != final or room.max_depth != final:
            err(room, "max_depth", f"boss rooms sit only at FINAL_DEPTH ({final}): min_depth and max_depth must both be {final}")
        if room.spawns and not any(s.class_ == "boss" for s in room.spawns):
            report.warn(room.row.file, room.row.line, "kind", "boss", "a boss room without a boss-class spawn")
    for room in rooms:
        if room.kind not in ("safe", "boss") and room.max_depth >= final:
            err(room, "max_depth", f"only boss rooms reach FINAL_DEPTH ({final}); use at most {final - 1}")

    for depth in range(1, final):
        eligible = [r for r in rooms if r.kind not in ("safe", "boss") and r.min_depth <= depth <= r.max_depth]
        if not eligible:
            report.error("rooms", None, "min_depth", str(depth), f"no combat or elite room is eligible at depth {depth}")
        elif len(eligible) == 1:
            report.warn("rooms", None, "min_depth", str(depth), f"only one room ({eligible[0].id}) is eligible at depth {depth}: the second exit stays empty")


def goal_rust(room: Room) -> str:
    return "RoomGoal::None" if room.kind == "safe" else "RoomGoal::KillAll"


def reward_rust(room: Room) -> str:
    if room.reward == "gold":
        return f"RoomReward::Gold({room.reward_amount})"
    if room.reward == "neutral_item":
        return "RoomReward::NeutralItem"
    return "RoomReward::None"


def spawn_rust(spawn: Spawn) -> str:
    return (
        f"RoomSpawn {{ ranged: {'true' if spawn.ranged else 'false'}, class: CreepClass::{CLASSES[spawn.class_]}, "
        f"count: {spawn.count}, offset: Vec2::new({f32(spawn.x)}, {f32(spawn.z)}) }}"
    )


def room_rust(room: Room) -> str:
    spawns = ", ".join(spawn_rust(s) for s in room.spawns)
    return (
        f"RoomDefinition {{ id: RoomId::{room.variant}, name: {rust_str(room.name)}, kind: RoomKind::{KINDS[room.kind]}, "
        f"layout: RoomLayoutId::{to_pascal_case(room.layout)}, min_depth: {room.min_depth}, max_depth: {room.max_depth}, "
        f"weight: {room.weight}, goal: {goal_rust(room)}, reward: {reward_rust(room)}, "
        f"shop: {'true' if room.shop else 'false'}, description: {rust_str(room.description)}, spawns: &[{spawns}] }}"
    )


def render(rooms: list[Room]) -> str:
    final = final_depth(rooms)
    out = [HEADER]
    out.append("/// Depth of the boss room: clearing it wins the run.")
    out.append(f"pub const FINAL_DEPTH: u32 = {final};\n")
    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
    out.append("pub enum RoomId {")
    out += [f"    {room.variant}," for room in rooms]
    out.append("}\n")
    out.append("pub static ROOMS: &[RoomDefinition] = &[")
    out += [f"    {room_rust(room)}," for room in rooms]
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    repo_default = Path(__file__).resolve().parents[1]
    parser.add_argument("rooms", type=Path, nargs="?", help="rooms CSV (default: data/rooms.csv)")
    parser.add_argument("spawns", type=Path, nargs="?", help="room spawns CSV (default: data/room_spawns.csv)")
    parser.add_argument("--repo-root", type=Path, default=repo_default, help="repository root (default: parent of scripts/)")
    parser.add_argument("--check", action="store_true", help="validate the CSVs without writing anything")
    parser.add_argument("--dry-run", action="store_true", help="print the generated Rust instead of writing it")
    args = parser.parse_args()

    repo = args.repo_root.resolve()
    rooms_csv = args.rooms or repo / "data" / "rooms.csv"
    spawns_csv = args.spawns or repo / "data" / "room_spawns.csv"
    catalog = repo / CATALOG_PATH

    rooms, report = load(rooms_csv, spawns_csv, find_layouts(repo))
    report.fail_if_errors()
    report.print()
    spawn_total = sum(len(room.spawns) for room in rooms)
    print(f"Validated {len(rooms)} room(s) with {spawn_total} spawn group(s); FINAL_DEPTH {final_depth(rooms)}.")
    if args.check:
        return 0

    generated = render(rooms)
    if args.dry_run:
        print(generated)
        print("Dry run — no files written.")
        return 0
    catalog.write_text(generated, encoding="utf-8")
    rustfmt(catalog)
    print(f"Wrote {catalog.relative_to(repo)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
